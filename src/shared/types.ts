// Types shared by the Worker (src/worker) and the app (src/app).

export type Role = 'user' | 'assistant'

export interface Conversation {
  id: string
  title: string
  model: string
  /** Set when the conversation is bound to an event's planning chat. */
  eventId: string | null
  createdAt: number
  updatedAt: number
}

export interface Message {
  id: string
  conversationId: string
  role: Role
  content: string
  model: string | null
  /** True when generation stopped before the model finished. */
  interrupted: boolean
  createdAt: number
}

export interface ModelInfo {
  id: string
  name: string
  description: string
  /** Whether the Freebuff API currently offers this model. */
  available: boolean
}

export interface Me {
  user: { sub: string; name?: string; email?: string; picture?: string }
  capabilities: {
    /** An API key is configured on the server. Never the key itself. */
    ai: boolean
    database: boolean
    auth: 'freebuff' | 'development'
  }
  usage: { used: number; limit: number; resetsAt: number }
}

/** Server-sent events on POST /api/chat. */
export type ChatEvent =
  | { type: 'start'; conversation: Conversation; userMessage: Message; assistantMessageId: string }
  | { type: 'delta'; text: string }
  | { type: 'done'; message: Message; usage: Me['usage'] }
  | { type: 'error'; code: string; message: string }

// --- Events and plans -------------------------------------------------------
// The plan itself is generated by deterministic logic in shared/planner.ts and
// validated there before anything from the model is applied to it.

export type EventKind = 'wedding' | 'birthday' | 'community'

export interface PlanEvent {
  id: string
  kind: EventKind
  title: string
  /** ISO date (yyyy-mm-dd). */
  date: string
  city: string
  guests: number
  budgetTotal: number
  /** Free-text notes (vibe, dietary needs, traditions) fed to the assistant. */
  details: string
  plan: Plan
  createdAt: number
  updatedAt: number
}

/** One share of the budget, in the event's currency. */
export interface BudgetLine {
  category: string
  amount: number
  note?: string
}

export type MilestoneScope = 'book' | 'send' | 'buy' | 'confirm' | 'prep'

export interface Milestone {
  label: string
  scope: MilestoneScope
  /** Absolute ISO date the milestone should be done by. */
  due: string
  done: boolean
}

export interface VendorItem {
  category: string
  label: string
  essential: boolean
  booked: boolean
  note?: string
}

export interface Plan {
  budget: { lines: BudgetLine[]; total: number; /** Per-guest floors squeezed another categories out of their normal share. */ stretched: boolean }
  timeline: Milestone[]
  vendors: VendorItem[]
  /** Ideas the assistant suggested and the host chose to keep. */
  ideas: string[]
  /** How the plan was last changed: the engine, a manual edit, or an applied AI proposal. */
  source: 'engine' | 'manual' | 'ai'
  updatedAt: number
}

/** Sections of a plan an edit may touch. */
export type PlanBudgetLineInput = { category?: unknown; amount?: unknown; note?: unknown }
export type PlanMilestoneInput = { label?: unknown; due?: unknown; scope?: unknown; done?: unknown }
export type PlanVendorInput = { label?: unknown; category?: unknown; essential?: unknown; booked?: unknown; note?: unknown }
export type PlanEditInput = {
  budgetLines?: PlanBudgetLineInput[]
  timeline?: PlanMilestoneInput[]
  vendors?: PlanVendorInput[]
  ideas?: unknown[]
}

/** Sent by the chat page when the host applies an assistant proposal. */
export type PlanProposal = {
  insertBudgetLines?: PlanBudgetLineInput[]
  /** Adds milestones, or refreshes ones the plan already has (matched by label). */
  insertTimeline?: PlanMilestoneInput[]
  budgetLines?: PlanBudgetLineInput[]
  timeline?: PlanMilestoneInput[]
  /** Adds vendors, or updates ones the plan already has (matched by category+label). */
  insertVendors?: PlanVendorInput[]
  vendors?: PlanVendorInput[]
  insertIdeas?: string[]
}

/** Toggle ops from the event page: flip a milestone, book a vendor, drop an idea. */
export type PlanToggle = { milestone?: number; vendor?: number; idea?: number }

export interface EventThread {
  event: PlanEvent
  /** The conversation bound to this event, if one exists. */
  threadId: string | null
}
